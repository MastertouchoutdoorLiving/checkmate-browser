// Bridge for the built-in iMessage page.
const { contextBridge, ipcRenderer } = require('electron')
contextBridge.exposeInMainWorld('imsg', {
  status: () => ipcRenderer.invoke('imsg:status'),
  chats: () => ipcRenderer.invoke('imsg:chats'),
  messages: (chatId) => ipcRenderer.invoke('imsg:messages', chatId),
  sendToChat: (guid, text) => ipcRenderer.invoke('imsg:send-chat', guid, text),
  sendToHandle: (handle, text) => ipcRenderer.invoke('imsg:send-handle', handle, text),
  prefs: () => ipcRenderer.invoke('imsg:prefs'),
  setPrefs: (p) => ipcRenderer.invoke('imsg:set-prefs', p),
  sendFile: (target, name, bytes) => ipcRenderer.invoke('imsg:send-file', target, name, bytes),
  clipboardFiles: () => ipcRenderer.invoke('imsg:clipboard-files'),
  contacts: () => ipcRenderer.invoke('imsg:contacts'),
  addContact: (c) => ipcRenderer.invoke('imsg:add-contact', c),
  whatsapp: (phone, text) => ipcRenderer.invoke('imsg:whatsapp', phone, text),
  revealAttachment: (id) => ipcRenderer.send('imsg:reveal-attachment', id),
  openUrl: (url) => ipcRenderer.send('imsg:open-url', url),
  openInMessages: (handle) => ipcRenderer.send('imsg:open-messages', handle),
  openPrivacySettings: () => ipcRenderer.send('imsg:open-privacy'),
  timers: () => ipcRenderer.invoke('timers:list'),
  remind: (r) => ipcRenderer.invoke('timers:remind', r),
  schedule: (m) => ipcRenderer.invoke('timers:schedule', m),
  cancelTimer: (id) => ipcRenderer.invoke('timers:cancel', id),
  onTimers: (fn) => ipcRenderer.on('timers:changed', (e, t) => fn(t)),
  jtStatus: () => ipcRenderer.invoke('jt:status'),
  jtSetKey: (k) => ipcRenderer.invoke('jt:set-key', k),
  jtSetOn: (on) => ipcRenderer.invoke('jt:set-on', on),
  jtAdd: (c) => ipcRenderer.invoke('jt:add', c),
  jtOpen: (url) => ipcRenderer.send('jt:open', url),
  quickReplies: () => ipcRenderer.invoke('qr:list'),
  setQuickReplies: (l) => ipcRenderer.invoke('qr:set', l),
  onQuickReplies: (fn) => ipcRenderer.on('qr:changed', (e, l) => fn(l)),
  unifiedList: () => ipcRenderer.invoke('unified:list'),
  unifiedOpen: (it) => ipcRenderer.invoke('unified:open', it),
  alerts: () => ipcRenderer.invoke('imsg:alerts'),
  setAlerts: (p) => ipcRenderer.invoke('imsg:set-alerts', p),
  viewing: (guid) => ipcRenderer.send('imsg:viewing', guid || null),
  onOpenChat: (fn) => ipcRenderer.on('imsg:open-chat', (e, guid) => fn(String(guid))),
  onAlertsChanged: (fn) => ipcRenderer.on('imsg:alerts-changed', (e, a) => fn(a)),
})
